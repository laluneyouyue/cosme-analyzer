# =============================================================================
# LLM に送るプロンプト
# =============================================================================
# プロンプトはこのアプリで最も頻繁に書き換わる部分です。
# 処理の流れ（analyzer.py）と混ざっていると、
# 「文言を1行直したいだけ」なのに解析ロジック全体を読む羽目になります。
# そのため文言だけをこのファイルに切り出しています。
#
# 【重要な設計変更】
# LLM に点数を出させるのをやめました。ここで頼むのは「分類」だけです。
#   ・各成分が5つの軸にどれくらい効くか（0〜3の4段階）
#   ・刺激になりうるか（0〜3）
#   ・少量でも効く成分か
# 点数の計算は scoring.py が行います。
#
# その結果、プロンプトにユーザーのプロフィール（肌質・年齢など）を
# 一切含めなくてよくなりました。副次的な効果が2つあります。
#   ・利用者の肌質などの個人情報を OpenAI に送らずに済む
#   ・同じ製品なら常に同じ分類結果になるので、将来キャッシュできる
#
# 【中括弧の扱いに注意】
#   f文字列（f"""..."""）の中では、JSONの { } をそのまま書くと
#   変数の埋め込み記号と解釈されてしまいます。
#   そのため f文字列の中だけ {{ }} と2つ重ねて書きます。
#   ふつうの文字列では1つのままで構いません。
# =============================================================================

import config


# =============================================================================
# 分類のしかたの説明（複数のプロンプトで使い回す）
# =============================================================================
# 0〜100 ではなく 0〜3 の4段階にしているのは、そのほうが LLM の答えが
# 安定するためです。「70点と75点の違い」は人間でも説明できませんが、
# 「強い／中くらい／弱い／なし」なら一貫して答えられます。
# =============================================================================

CLASSIFICATION_RULES = f"""
【評価する5つの軸】
- moisturizing : {config.AXIS_LABELS["moisturizing"]}（例: グリセリン、ヒアルロン酸Na、セラミド）
- soothing     : {config.AXIS_LABELS["soothing"]}（例: ツボクサエキス、アラントイン、パンテノール）
- anti_aging   : {config.AXIS_LABELS["anti_aging"]}（例: レチノール、各種ペプチド、ナイアシンアミド）
- brightening  : {config.AXIS_LABELS["brightening"]}（例: ビタミンC誘導体、トラネキサム酸、アルブチン）
- pore         : {config.AXIS_LABELS["pore"]}（例: サリチル酸、クレイ、ナイアシンアミド）

【各軸のつけ方（0〜3の4段階）】
  3 = その効果の主役といえる成分
  2 = はっきり寄与する成分
  1 = 間接的・副次的に寄与する成分
  0 = その効果とは関係がない

【重要】成分を「代表的な効果ひとつ」に決めつけないでください。
ひとつの成分が複数の軸に効くことは珍しくありません。
成分ごとに5軸すべてを順に検討し、少しでも寄与するなら 1 を付けてください。

  ナイアシンアミド … 透明感3 / ハリ2 / 毛穴2 / 保湿1
  パンテノール     … 鎮静3 / 保湿2
  セラミドNP       … 保湿3 / 鎮静1（バリア機能を助けるので肌あれにも寄与する）
  シアバター       … 保湿3 / ハリ1（やわらかさ・ふっくら感）
  トコフェロール   … ハリ1 / 透明感1（抗酸化）
  アラントイン     … 鎮静3 / 保湿1

逆に、次のような成分は製品の土台や補助であって効果を担っていないので、
5軸すべて0で構いません。
  防腐剤、pH調整剤、キレート剤、増粘剤、乳化剤、溶剤、着色料、香料

ただしこれは「5軸の効果」の話です。刺激リスクは別に判定してください。
効果が0の成分でも、刺激になりうるなら irritation_risk には点を付けてください。

【irritation_risk（刺激リスク・0〜3）】
  3 = 刺激が強く、敏感肌では避けられることが多い（例: 高濃度エタノール、メントール）
  2 = 人によって刺激になりうる（例: 香料、精油、着色料）
  1 = まれに反応する人がいる
  0 = ほとんど刺激にならない

【low_dose_active（少量でも効く成分か）】
  true  = 配合量が少なくても効果を発揮する成分（例: レチノール、ナイアシンアミド、ペプチド）
  false = 配合量が多いほど効く一般的な成分（例: グリセリン、各種オイル）

【position】
  成分表に書かれている順番を、1から数えてそのまま入れてください。
  全成分表示は配合量の多い順に並ぶため、この順番が配合量の手がかりになります。

【注意】
- 水（Water / Aqua / 精製水）はほぼ全ての化粧品に含まれる当たり前の成分なので、含めないでください
- 成分が多い場合は、先頭から最大{config.MAX_INGREDIENTS}種類までにしてください
- 点数や相性の判定はこちらで行うので、あなたは分類だけしてください
"""


# 返答してほしい JSON の形（複数のプロンプトで使い回す）
