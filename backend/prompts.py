# =============================================================================
# 成分が読み取れたとき: 成分を分類する
# =============================================================================

def build_classification_prompt(ingredients_text: str, product_name: str = "") -> str:
    """読み取れた成分テキストを、軸ごとの分類データに変換させるプロンプト。

    ユーザーのプロフィールは一切渡しません。
    「この成分は何に効くか」は誰にとっても同じ事実なので、
    人によって変わる判断（相性・点数）は Python 側で行います。
    """
    name_hint = f"\n【製品名の手がかり】\n{product_name}\n" if product_name else ""

    return f"""
あなたはコスメ成分の専門家です。
以下の成分表を読み、成分を1つずつ分類してください。
{name_hint}
【成分表】
{ingredients_text}

【手順】
1. 成分名が外国語（韓国語・英語など）の場合は日本語に翻訳する
2. 各成分を下記の基準で分類する
{CLASSIFICATION_RULES}

【返答形式】
必ず以下の JSON 形式のみで返答してください。それ以外のテキストは一切含めないでください。
{OUTPUT_FORMAT}
"""


# =============================================================================
# 成分が読み取れなかったとき: Web検索して成分を調べ、分類する
# =============================================================================

def build_search_and_classify_prompt(product_name: str) -> str:
    """商品名から Web 検索で成分を調べ、そのまま分類まで行うプロンプト。"""
    return f"""
あなたはコスメ成分の専門家です。
「{product_name}」というコスメ製品の全成分を Web で検索して調べてください。

成分が判明したら、成分を1つずつ分類してください。

【手順】
1. Web検索で「{product_name}」の全成分を調べる
2. 成分名が外国語（韓国語・英語など）の場合は日本語に翻訳する
3. 各成分を下記の基準で分類する
{CLASSIFICATION_RULES}

【返答形式】
JSON のみで返答してください（説明文・引用・コードブロックは不要）。
{OUTPUT_FORMAT}
"""
