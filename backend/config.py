# =============================================================================
# アプリの設定値
# =============================================================================
# 環境変数の読み込みと、アプリ全体で使う定数をここに集約しています。
#
# 【なぜ設定を1か所に集めるのか】
# 「本番とローカルで値が変わるもの」「あとから調整したくなる数字」が
# コードのあちこちに散らばっていると、変更のたびに全ファイルを探すことになります。
# ここだけ見れば、このアプリが外部から受け取る設定と、
# 採点に使っている数字が全部わかる状態にしています。
# =============================================================================

import os
from pathlib import Path

# python-dotenv: .envファイルから環境変数を読み込むライブラリ
from dotenv import load_dotenv

# .envファイルを読み込む（APIキーなどの秘密情報をコードに直接書かないための仕組み）
# このファイルが最初に import されるので、ここで一度だけ実行される
load_dotenv()


# =============================================================================
# OpenAI
# =============================================================================

OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY")

# 使用するモデル。工程ごとに分けてあるのは、あとから
# 「画像を読む工程だけ上位モデルにする」といった調整をしたいため。
VISION_MODEL = "gpt-4o-mini"    # Step 1: 画像から成分表を読み取る
ANALYSIS_MODEL = "gpt-4o-mini"  # 成分の分類 / Web検索

# timeout: 応答が返ってこないときに何秒で諦めるか。
#   指定しないと延々と待ち続け、画面が固まったままになる。
#   Cloudflare は100秒でリクエストを打ち切るため、それより短くしておく。
OPENAI_TIMEOUT = 60.0

# max_retries: 失敗時の自動リトライ回数。多いと待ち時間が伸びるので1回に抑える。
OPENAI_MAX_RETRIES = 1

# 出力の上限。成分リストが長くなって JSON が途中で切れるのを防ぐ。
MAX_OUTPUT_TOKENS = 8192

# LLM に書き出させる成分の上限件数
MAX_INGREDIENTS = 30


# =============================================================================
# アクセス制御
# =============================================================================

# 許可するアクセス元（オリジン）は環境変数から読み込む。
# ローカル開発では Vite の開発サーバー、本番では Cloudflare Pages のURLになるため、
# コードに直接書かず、環境ごとに差し替えられるようにする。カンマ区切りで複数指定可。
ALLOWED_ORIGINS = [
    origin.strip()
    for origin in os.environ.get(
        "ALLOWED_ORIGINS", "http://localhost:5173,http://localhost:3000"
    ).split(",")
    if origin.strip()
]

# 合言葉。Cloudflare 経由で来たリクエストかどうかを判定するために使う。
# 未設定（ローカル開発時）ならチェックは行わない。
APP_SECRET = os.environ.get("APP_SECRET", "")


# =============================================================================
# 画像の受け入れ条件
# =============================================================================

# 受け付ける画像の上限サイズ（10MB）。
# フロント側で送信前に縮小しているので通常は1MB未満だが、
# 巨大なファイルでサーバのメモリを食い潰されないための保険。
MAX_IMAGE_BYTES = 10 * 1024 * 1024

# 受け付ける画像の種類。HEIC などは OpenAI 側が扱えないため弾く。
ALLOWED_IMAGE_TYPES = {"image/jpeg", "image/jpg", "image/png", "image/webp"}


# =============================================================================
# 評価の5軸
# =============================================================================
# 軸を選ぶ基準は2つ:
#   ① 成分表から判定できること（LLMが根拠を持って答えられる）
#   ② ユーザーが自分で答えられること（プロフィール側で選べる）
# この2つを満たさないものは軸にしない。
#
# 「安全性」を軸から外しているのは、性質が違うため。
# 効果の軸は「人によって要る／要らない」が、安全性は「全員が高いほうがいい」。
# 混ぜると同じ形で並んでしまい意味が読めなくなるので、刺激リスクとして別に扱う。
# =============================================================================

AXES = ["moisturizing", "soothing", "anti_aging", "brightening", "pore"]

AXIS_LABELS = {
    "moisturizing": "保湿・うるおい",
    "soothing": "鎮静・肌あれケア",
    "anti_aging": "ハリ・エイジングケア",
    "brightening": "透明感・くすみケア",
    "pore": "毛穴・皮脂ケア",
}


# =============================================================================
# 採点に使う数字（すべて調整可能）
# =============================================================================

# --- 配合量の重み ---------------------------------------------------------
# 全成分表示は配合量の多い順に並ぶ規則があるため、成分表の順番を
# 「どれくらい入っているか」の代理指標として使う。
# 後ろの成分ほど軽く扱うが、下限を設けて完全には無視しない。
MIN_WEIGHT = 0.3

# --- 軸スコアの正規化 -----------------------------------------------------
# 重み付き合計がこの値に達したら100点とする。
# 6.0 は「最も強い成分(3)が上位に2つあれば満点」という想定。
AXIS_FULL_SCORE = 6.0

# --- あなたが求めるもの（レーダーの内側）-----------------------------------
NEED_SELECTED = 100  # 重視する効果として選んだ軸
# 選んでいない軸の基準線。「あれば嬉しい」程度の扱い。
# ここを高くしすぎると、求めていない軸の達成分がスコアを押し上げてしまい、
# 「重視した効果が足りないのに高得点」という逆転が起きるため低めにしている。
NEED_BASELINE = 15

# 年齢によって「必要なもの」が変わる分の補正。
# 同じ成分でも年代によって「良い」の意味が変わるため、要求側を動かす。
AGE_ADJUSTMENTS = {
    "10代":     {"anti_aging": -20, "pore": 20},
    "20代":     {"pore": 10},
    "30代":     {"anti_aging": 10},
    "40代":     {"anti_aging": 20, "moisturizing": 10},
    "50代以上": {"anti_aging": 25, "moisturizing": 15},
}

# --- 減点 -----------------------------------------------------------------
# 「避けたい成分」に該当した場合の減点（1件ごと／合計の上限）
AVOID_PENALTY_PER_HIT = 15
AVOID_PENALTY_MAX = 30

# 刺激リスクによる減点。敏感肌の人には強く効かせる。
IRRITATION_PENALTY_SENSITIVE = {"低": 0, "中": 10, "高": 20}
IRRITATION_PENALTY_NORMAL = {"低": 0, "中": 0, "高": 10}

# 刺激リスクを「低・中・高」に切り分ける境目（重み付き合計に対して）
IRRITATION_THRESHOLD_LOW = 1.5   # これ未満なら「低」
IRRITATION_THRESHOLD_HIGH = 3.5  # これ以上なら「高」、間は「中」

# 刺激に弱いとみなす肌質
SENSITIVE_SKIN_TYPES = {"敏感肌", "アトピー肌"}

# --- 成分の表示 -----------------------------------------------------------
# 成分表の上位何割までを「配合上位」バッジの対象にするか
TOP_RANKED_RATIO = 0.3

# 「この軸に効いています」として画面に出す成分の件数
MAX_CONTRIBUTORS_PER_AXIS = 3


# =============================================================================
# 出力の検証（verification.py で使う）
# =============================================================================
# LLM が返した成分を、Step 1 で読み取った元の成分表と突き合わせるための設定。

# 「元の成分表に載っている」と認める一致度の下限 (0.0〜1.0)。
# 完全一致だけを認めると "水酸化Na" と "水酸化ナトリウム" が別物になるため、
# 2文字の並びがどれくらい共通しているかで測り、6割以上あれば同じとみなす。
VERIFY_MATCH_THRESHOLD = 0.6

# この文字数以下の成分名は、完全一致でしか認めない。
# 短い語は偶然一致してしまい、でっちあげを見逃す原因になるため。
VERIFY_EXACT_ONLY_LENGTH = 3

# 照合結果を採用する条件。LLM が返した成分のうち、これ未満しか
# 元の成分表と一致しなかった場合は「照合のしかたが合っていない」と判断し、
# 何も除外しない。本物を消してしまう方が害が大きいため。
VERIFY_MIN_MATCH_RATIO = 0.5

# 取りこぼし率（%）がこの値以上なら、読み取り不安定として画面で警告する
OMISSION_WARN_RATE = 30


# =============================================================================
# デバッグ用のログ
# =============================================================================

# LLM のやり取りをファイルに保存するか。
# 本番では保存しない（ユーザーの肌質などの情報をサーバに残さないため）。
# ローカルでデバッグしたいときだけ .env に SAVE_LLM_LOGS=true と書く。
SAVE_LLM_LOGS = os.environ.get("SAVE_LLM_LOGS", "false").lower() == "true"

# ログの保存先ディレクトリ（このファイルと同じ階層に logs/ を作る）
LOG_DIR = Path(__file__).parent / "logs"
